async def filtered_response_for_sub_acct_list(filtered_acct_type_list, core):
  # self.logger.info("ENTERED INTO FILTERED RESPONSE FUNCTION ")
  core_response_api = []

  # print('filtered_acct_type_list', filtered_acct_type_list)

  def get_fiserv_response(acct_type_details):
    rate_tier = acct_type_details["BalanceCategoryBalanceTypes"][0][
        "RateTiers"][0] if acct_type_details.get(
            "BalanceCategoryBalanceTypes") else {}
    return {
        "description": acct_type_details.get("Description", ""),
        "account_type": "TD",
        "sub_account_type": acct_type_details.get("MinorAccountTypeCode", ""),
        "interest_rate": rate_tier.get("Rate", 0)
    }

  def get_symitar_response(acct_type_details):
    return {
        "description": acct_type_details.get("Description", ""),
        "account_type": acct_type_details.get("ShareCode", ""),
        "sub_account_type": acct_type_details.get("ShareType", ""),
        "interest_rate": acct_type_details.get("DivRate", 0)
    }

  response_functions = {
      "FISERV": get_fiserv_response,
      "SYMITAR": get_symitar_response
  }

  response_function = response_functions.get(core)
  print("\n response function is ", response_function)
  core_response_api = [
      response_function(acct_type_details)
      for acct_type_details in filtered_acct_type_list
  ]

  return core_response_api


